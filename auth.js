/* Student authentication and membership gate for My Study Station Pro Learning */
const byId = (id) => document.getElementById(id);

const showMessage = (message, isError = false) => {
  const el = byId("message");
  if (el) {
    el.textContent = message;
    el.className = "message " + (isError ? "error" : "success");
  }
};

async function loadSchools() {
  const select = byId("school");
  if (!select) return;
  try {
    const { data, error } = await supabaseClient
      .from("schools")
      .select("id,school_name,is_verified")
      .eq("is_verified", true)
      .order("school_name");
    if (error) {
      console.warn("School list unavailable:", error.message);
      return;
    }
    for (const school of data || []) {
      const option = document.createElement("option");
      option.value = school.id;
      option.textContent = school.school_name;
      select.appendChild(option);
    }
  } catch (error) {
    console.warn("School list unavailable:", error.message);
  }
}
loadSchools();

const registerForm = byId("register-form");
if (registerForm) registerForm.addEventListener("submit", async (event) => {
  event.preventDefault();
  const displayName = byId("display-name").value.trim();
  const email = byId("email").value.trim().toLowerCase();
  const password = byId("password").value;
  const confirmPassword = byId("confirm-password").value;
  const schoolId = byId("school")?.value || null;

  if (password.length < 8) return showMessage("Use a password with at least 8 characters.", true);
  if (password !== confirmPassword) return showMessage("The passwords do not match.", true);

  const button = registerForm.querySelector("button[type=submit]");
  button.disabled = true;
  button.textContent = "Creating account…";
  try {
    const { data, error } = await supabaseClient.auth.signUp({
      email,
      password,
      options: {
        data: { display_name: displayName, school_id: schoolId },
        emailRedirectTo: window.location.origin + "/login.html"
      }
    });
    if (error) throw error;
    if (data.user) {
      showMessage("Registration submitted. Check your email for the confirmation link. Your student number is generated by the database after confirmation.");
      registerForm.reset();
    } else {
      showMessage("Please check your email to continue.");
    }
  } catch (error) {
    showMessage(error.message || "Registration failed. Please try again.", true);
  } finally {
    button.disabled = false;
    button.textContent = "Create student account";
  }
});

async function checkMembership(userId) {
  const { data, error } = await supabaseClient
    .from("memberships")
    .select("status,expires_at,created_at")
    .eq("user_id", userId)
    .order("created_at", { ascending: false })
    .limit(1)
    .maybeSingle();

  if (error) throw new Error("We could not verify your subscription. Please try again.");
  if (!data) return { active: false, status: "not_active", expiresAt: null };

  const status = String(data.status || "").toLowerCase();
  const expiryMs = data.expires_at ? Date.parse(data.expires_at) : NaN;
  const active = status === "active" && Number.isFinite(expiryMs) && expiryMs > Date.now();
  return {
    active,
    status: active ? "active" : (status || "expired"),
    expiresAt: data.expires_at || null
  };
}

const loginForm = byId("login-form");
if (loginForm) loginForm.addEventListener("submit", async (event) => {
  event.preventDefault();
  const email = byId("email").value.trim().toLowerCase();
  const password = byId("password").value;
  const button = loginForm.querySelector("button[type=submit]");
  button.disabled = true;
  button.textContent = "Logging in…";
  try {
    const { data, error } = await supabaseClient.auth.signInWithPassword({ email, password });
    if (error) throw error;
    if (!data.session || !data.user) {
      showMessage("Please confirm your email before logging in.", true);
      return;
    }
    showMessage("Checking your membership…");
    const membership = await checkMembership(data.user.id);
    if (membership.active) window.location.replace("pro.html");
    else window.location.replace("subscription-expired.html");
  } catch (error) {
    showMessage(error.message || "Login failed. Please try again.", true);
  } finally {
    button.disabled = false;
    button.textContent = "Log in";
  }
});

const resetLink = byId("reset-link");
if (resetLink) resetLink.addEventListener("click", async (event) => {
  event.preventDefault();
  const email = byId("email").value.trim().toLowerCase();
  if (!email) return showMessage("Enter your email address first.", true);
  const { error } = await supabaseClient.auth.resetPasswordForEmail(email, {
    redirectTo: window.location.origin + "/login.html"
  });
  showMessage(error ? error.message : "If this email is registered, a password reset link will be sent.", !!error);
});
